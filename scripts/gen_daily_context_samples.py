    print(f"Generating {len(SAMPLES)} samples to {OUT_FILE}")

    with open(OUT_FILE, "w", encoding="utf-8") as f:
        json.dump(SAMPLES, f, ensure_ascii=False, indent=2)

    # 统计
    categories = {}
    for s in SAMPLES:
        cat = s.get("_category", "general")
        categories[cat] = categories.get(cat, 0) + 1

    total_chars = sum(len(s["output"]) for s in SAMPLES)
    avg_chars = total_chars / len(SAMPLES)

    print(f"  Done: {len(SAMPLES)} samples")
    print(f"  Categories: {categories}")
    print(f"  Avg output length: {avg_chars:.0f} chars")
    print(f"  Output: {os.path.abspath(OUT_FILE)}")

    return 0


